// Turns the @primer/primitives colour tokens into CSS custom properties, one
// block per theme and mode (TECH.md §6). Run with `pnpm build:tokens`; the
// output is committed, and a test fails when it's stale.
import { readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

/** Each theme names the Primer token file for each mode. */
export const THEMES = [{ name: 'github', modes: { light: 'light', dark: 'dark' } }];

export const OUTPUT = join(dirname(fileURLToPath(import.meta.url)), '../src/styles/themes.css');

const require = createRequire(import.meta.url);
const primerDir = dirname(require.resolve('@primer/primitives/package.json'));

/** The generated stylesheet. The same package version gives the same output. */
export function render() {
  const { version } = JSON.parse(readFileSync(join(primerDir, 'package.json'), 'utf8'));
  let css =
    `/* Generated by scripts/build-tokens.js from @primer/primitives ${version}.\n` +
    ' * Do not edit. Run `pnpm build:tokens` instead. */\n';
  for (const theme of THEMES) {
    for (const [mode, file] of Object.entries(theme.modes)) {
      const path = join(primerDir, 'dist/docs/functional/themes', `${file}.json`);
      const tokens = Object.values(JSON.parse(readFileSync(path, 'utf8')));
      tokens.sort((a, b) => (a.name < b.name ? -1 : a.name > b.name ? 1 : 0));
      css += `\n[data-theme='${theme.name}'][data-mode='${mode}'] {\n`;
      css += `  color-scheme: ${mode};\n`;
      for (const token of tokens) {
        css += `  --${token.name}: ${token.value};\n`;
      }
      css += '}\n';
    }
  }
  return css;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  writeFileSync(OUTPUT, render());
  console.log(`Wrote ${OUTPUT}`);
}
