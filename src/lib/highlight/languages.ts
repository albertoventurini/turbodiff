/** The language of the file at `path`, from its name or extension, or `null`. */
export function languageFor(path: string): LanguageId | null {
  const name = path.slice(path.lastIndexOf('/') + 1).toLowerCase();
  if (Object.hasOwn(NAMES, name)) return NAMES[name];
  const dot = name.lastIndexOf('.');
  if (dot <= 0) return null;
  const extension = name.slice(dot + 1);
  return Object.hasOwn(EXTENSIONS, extension) ? EXTENSIONS[extension] : null;
}
